#!/bin/zsh
# Показать знакомство заново, ничего не ломая: модель и выданные доступы
# остаются на месте. Приложение само считает знакомство пройденным, если
# модель на месте и доступы выданы, поэтому просим его прямо — ключом
# --setup.
set -e
osascript -e 'quit app "Giga Pisar"' 2>/dev/null || true
sleep 1
open "/Applications/Giga Pisar.app" --args --setup
echo "Окно знакомства появится через полсекунды."
