"""Пунктуация по правилам для казахского текста из multilingual_ctc.

Модель выдаёт поток строчных слов без знаков. Здесь по паузам между словами
и по окончаниям расставляются точки, запятые, вопросы и заглавные.

Казахский — язык SOV: сказуемое стоит в конце предложения. Поэтому точку
на паузе ставим только после формы сказуемого, а запятую — на паузе после
деепричастия или условной формы (граница придаточного).

Эталон для swift/KazakhPunct.swift: оба обязаны выдавать один и тот же текст.
"""
from __future__ import annotations

PAUSE = 0.6          # пауза после сказуемого — конец предложения
LONG = 1.5           # такая пауза — конец предложения почти при любом слове
COMMA_PAUSE = 0.35   # пауза после деепричастия — запятая

PRED = ("ды", "ді", "ты", "ті", "мыз", "міз", "быз", "біз", "пыз", "піз", "сыз", "сіз",
        "ңыз", "ңіз", "мын", "мін", "бын", "бін", "пын", "пін", "сың", "сің", "йды", "йді",
        "йық", "йік", "йміз", "ймыз", "йін", "йын", "шы", "ші", "бар", "жоқ", "емес", "екен",
        "керек", "мүмкін", "тұр", "отыр", "жатыр", "ған", "ген", "қан", "кен", "дық", "дік",
        "тық", "тік", "лық", "лік")
PRED_WORDS = {"бар", "жоқ", "емес", "екен", "еді"}
NOT_PRED = ("ларды", "лерді", "дарды", "дерді", "тарды", "терді", "дағы", "дегі", "тағы", "тегі")
CLAUSE = ("са", "се", "сақ", "сек", "саң", "сең", "саңыз", "сеңіз", "сам", "сем", "ып", "іп",
          "ғанда", "генде", "қанда", "кенде", "ғандықтан", "гендіктен", "ғанмен", "генмен",
          "майынша", "мейінше", "йынша", "йінше")
QUESTION = {"ма", "ме", "ба", "бе", "па", "пе"}
COMMA_BEFORE = {"бірақ", "алайда", "себебі", "өйткені", "яғни", "әйтпесе", "сондықтан"}
# с них начинается новое предложение: после сказуемого — точка даже без паузы
STARTERS = {"келесі", "біріншіден", "екіншіден", "үшіншіден", "төртіншіден", "сонымен",
            "сондықтан", "ал", "енді", "демек", "сол", "осылайша"}
# на них предложение не кончается: пауза после них — запинка
NO_END = {"біз", "бір", "сол", "ол", "осы", "бұл", "және", "мен", "немесе", "яғни",
          "ал", "мысалы", "оның", "біздің", "сіздер", "енді", "де", "да", "те", "та", "ең", "әр"}


def is_pred(w: str) -> bool:
    """Похоже ли слово на сказуемое (конец предложения)."""
    if w in PRED_WORDS:
        return True
    return len(w) > 3 and w.endswith(PRED) and not w.endswith(NOT_PRED)


def _cap(w: str) -> str:
    return w[:1].upper() + w[1:]


def punctuate(words, pause: float = PAUSE) -> str:
    """words: [(текст, начало_с, конец_с), ...] по порядку → текст со знаками."""
    sentences = []            # [(слова, знак в конце)]
    cur = []                  # слова текущего предложения (могут нести «,»)
    prev_end = 0.0
    for w, start, end in words:
        if cur:
            gap = start - prev_end
            prev = cur[-1]
            if prev in QUESTION and gap >= COMMA_PAUSE:
                sentences.append((cur, "?"))
                cur = []
            elif (gap >= LONG and prev not in NO_END) \
                    or (gap >= pause and is_pred(prev)) \
                    or (w in STARTERS and is_pred(prev) and prev not in NO_END):
                sentences.append((cur, "."))
                cur = []
            elif gap >= COMMA_PAUSE and prev.endswith(CLAUSE) and w not in COMMA_BEFORE:
                cur[-1] = prev + ","
        cur.append(w)
        prev_end = end
    if cur:
        sentences.append((cur, "."))
    return " ".join(_sentence(ws, mark) for ws, mark in sentences)


def _sentence(ws, mark: str) -> str:
    out = []
    for w in ws:
        if out and w in COMMA_BEFORE and not out[-1].endswith(","):
            out[-1] += ","
        out.append(w)
    # вопросительная частица посреди предложения: «сәлеметсіздер ме? құрметті…»
    last = len(out) - 1
    for k in range(last):
        if out[k] in QUESTION:
            out[k] += "?"
    for k in range(1, len(out)):
        if out[k - 1].endswith("?"):
            out[k] = _cap(out[k])
    text = " ".join(out).rstrip(",")
    return _cap(text) + mark
